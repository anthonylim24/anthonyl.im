type StyleXStyles = typeof styles

export function dateDayBtnState(isEdge: boolean, inBand: boolean, isToday: boolean): StyleXStyles[keyof StyleXStyles][] {
  const out: StyleXStyles[keyof StyleXStyles][] = [styles.dateDayBtn]
  if (!isEdge && !inBand) out.push(styles.dateDayBtnIdle)
  if (isToday && !isEdge) out.push(styles.dateDayBtnToday)
  return out
}

export function dateBandState(
  isStart: boolean,
  isEnd: boolean,
  bandedPrev: boolean,
  colIndex: number,
  bandedNext: boolean,
): StyleXStyles[keyof StyleXStyles][] {
  const out: StyleXStyles[keyof StyleXStyles][] = [styles.dateDayBand]
  if (isStart) out.push(styles.dateDayBandStart)
  else if (bandedPrev && colIndex % 7 !== 0) out.push(styles.dateDayBandMid)
  else out.push(styles.dateDayBandRoundL)
  if (isEnd) out.push(styles.dateDayBandEnd)
  else if (bandedNext && colIndex % 7 !== 6) out.push(styles.dateDayBandMid)
  else out.push(styles.dateDayBandRoundR)
  return out
}

export function dateDayNumState(isEdge: boolean, inBand: boolean): StyleXStyles[keyof StyleXStyles] {
  if (isEdge) return styles.dateDayNumEdge
  if (inBand) return styles.dateDayNumInBand
  return styles.dateDayNumDefault
}

